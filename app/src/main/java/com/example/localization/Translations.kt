package com.example.localization

import com.example.model.AppLanguage

object Translations {
    fun get(key: TranslationKey, language: AppLanguage): String {
        return when (language) {
            AppLanguage.ENGLISH -> englishMap[key] ?: key.name
            AppLanguage.HINDI -> hindiMap[key] ?: englishMap[key] ?: key.name
            AppLanguage.HINGLISH -> hinglishMap[key] ?: englishMap[key] ?: key.name
        }
    }
}

